func simulate(niter int, r *rand.Rand) {
	ch := make(chan [10]float64)
	for range runtime.NumCPU() {
		go func(r *rand.Rand) {
			wins5 := 0
			nbingos8sum := 0
			n5sum := 0
			n8sum := 0
			n5wsum := 0
			n8wsum := 0
			n5lsum := 0
			n8lsum := 0
			nbingos8wsum := 0
			nbingos8lsum := 0
			for range niter {
				win, nbingos, n5, n8 := alternativeTrial(r)
				if win {
					wins5++
					n5wsum += n5
					n8wsum += n8
					nbingos8wsum += nbingos
				} else {
					n5lsum += n5
					n8lsum += n8
					nbingos8lsum += nbingos
				}
				nbingos8sum += nbingos
				n5sum += n5
				n8sum += n8
			}
			ch <- [10]float64{float64(wins5) / float64(niter), float64(nbingos8sum) / float64(niter), float64(n5sum) / float64(niter), float64(n8sum) / float64(niter), float64(n5wsum) / float64(wins5), float64(n8wsum) / float64(wins5), float64(n5lsum) / float64(niter-wins5), float64(n8lsum) / float64(niter-wins5), float64(nbingos8wsum) / float64(wins5), float64(nbingos8lsum) / float64(niter-wins5)}
		}(rand.New(rand.NewSource(int64(r.Uint64()))))
	}
	sums := [10]float64{}
	for range runtime.NumCPU() {
		result := <-ch
		for i, s := range result {
			sums[i] += s
		}
	}
	// This is technically wrong for the averages when the 5×5 board wins or loses, since the averages need to be weighted to the number of wins or losses per CPU instead of weighting each CPU equally.  But it should be a good enough approximation when niters is sufficiently large.
	for _, s := range sums {
		fmt.Printf("%f\n", s/float64(runtime.NumCPU()))
	}
}

func calculateB5() {
	b := [1 << 25]bool{}
	for i := range 1 << 25 {
		if bingo5(uint64(i)) {
			b[i] = true
		}
	}
	num := [25]int{}
	denom := [25]int{}
	for i := range 1 << 25 {
		if b[i] {
			continue
		}
		n := bits.OnesCount(uint(i))
		for j := range 25 {
			k := i | (1 << j)
			if k == i {
				continue
			}
			denom[n]++
			if b[k] {
				num[n]++
			}
		}
	}
	for i := range num {
		if denom[i] != 0 {
			fmt.Printf("b5[%d] = %d/%d\n", i, num[i], denom[i])
		}
	}
}

func main() {
	const seed = 20260904
	r := rand.New(rand.NewSource(seed))

	const niter = 1000000
	simulate(niter, r)

	calculateB5()
}
